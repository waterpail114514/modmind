const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const file = pathToFileURL(path.resolve('prototypes/beginner-minimal.html')).href;
  const screenshot = name => page.screenshot({ path: path.resolve(`test-results/beginner-minimal/${name}.png`), fullPage: true });
  const clickAction = action => page.locator(`[data-action="${action}"]:visible`).click();
  await page.goto(file);
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.locator('.brand img').evaluate(img => img.decode());
  assert.equal(await page.locator('img:visible').count(), 1);
  assert.equal(await page.locator('.welcome h1').evaluate(el => getComputedStyle(el).fontSize), '29px');
  assert.equal(await page.locator('#send').isDisabled(), true);
  assert.equal(await page.getByLabel('模型', { exact: true }).inputValue(), 'gpt-5.6-sol');
  assert.equal(await page.getByLabel('思考强度', { exact: true }).inputValue(), 'medium');
  await screenshot('desktop-empty');
  await page.getByLabel('模型', { exact: true }).selectOption('gpt-5.6-terra');
  await page.getByLabel('思考强度', { exact: true }).selectOption('extreme');
  await page.reload();
  assert.equal(await page.getByLabel('模型', { exact: true }).inputValue(), 'gpt-5.6-terra');
  assert.equal(await page.getByLabel('思考强度', { exact: true }).inputValue(), 'extreme');
  await page.locator('#prompt').fill('做一把右键可以释放闪电的剑');
  await page.getByRole('checkbox', { name: '专业模式' }).check();
  assert.equal(await page.locator('#expert-sidebar').isVisible(), true);
  assert.equal(await page.locator('#prompt').inputValue(), '做一把右键可以释放闪电的剑');
  await screenshot('desktop-expert-empty');
  await page.getByRole('checkbox', { name: '专业模式' }).uncheck();
  await page.locator('#send').click();
  await page.locator('[data-version="1.20.1|Forge"]').click();
  assert.equal(await page.getByLabel('模型', { exact: true }).isDisabled(), true);
  assert.equal(await page.getByLabel('思考强度', { exact: true }).isDisabled(), true);
  await page.getByRole('checkbox', { name: '专业模式' }).check();
  assert.equal(await page.getByRole('button', { name: '停止制作', exact: true }).isVisible(), true);
  await page.getByRole('checkbox', { name: '专业模式' }).uncheck();
  await page.getByRole('button', { name: '停止制作', exact: true }).click();
  await page.getByRole('button', { name: '继续制作', exact: true }).click();
  await page.locator('.result').waitFor();
  assert.equal(await page.locator('.result-title').innerText(), '闪电剑');
  assert.equal(await page.locator('.item-canvas').getAttribute('data-item'), 'sword');
  assert.equal(await page.getByLabel('模型', { exact: true }).isEnabled(), true);
  await screenshot('desktop-conversation');
  await page.getByRole('checkbox', { name: '专业模式' }).check();
  await screenshot('desktop-expert-conversation');
  await page.getByRole('checkbox', { name: '专业模式' }).uncheck();
  const nonblank = await page.locator('.item-canvas').evaluate(canvas => {
    const pixels = canvas.getContext('2d').getImageData(0, 0, 32, 32).data;
    return pixels.filter((value, index) => index % 4 === 3 && value > 0).length;
  });
  assert.ok(nonblank > 50, 'Preview canvas should contain an item');
  await page.getByLabel('模型', { exact: true }).selectOption('gpt-5.6-sol');
  await page.getByLabel('思考强度', { exact: true }).selectOption('high');
  await page.locator('.preview-button').click();
  await page.getByRole('button', { name: '绿色', exact: true }).click();
  await page.getByRole('button', { name: '查看特效', exact: true }).click();
  const pngEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载贴图', exact: true }).click();
  const png = await pngEvent;
  assert.ok(png.suggestedFilename().endsWith('.png'));
  await screenshot('desktop-preview');
  await page.getByRole('button', { name: '应用颜色', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.result').length === 2);
  assert.equal(await page.locator('.item-canvas').last().getAttribute('data-color'), 'green');
  assert.equal(await page.locator('.item-canvas').last().getAttribute('data-item'), 'sword');
  await page.locator('[data-export]').last().click();
  const jsonEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: '作品草稿', exact: true }).click();
  const json = await jsonEvent;
  assert.ok(json.suggestedFilename().endsWith('-v2.json'));
  const exported = JSON.parse(fs.readFileSync(await json.path(), 'utf8'));
  const results = exported.messages.filter(m => m.kind === 'result');
  assert.deepEqual(results[0].generation, { model: 'gpt-5.6-terra', reasoningLevel: 'extreme', reasoningEffort: 'ultra' });
  assert.deepEqual(results[1].generation, { model: 'gpt-5.6-sol', reasoningLevel: 'high', reasoningEffort: 'xhigh' });
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.locator('#file-input').setInputFiles({ name: 'reference.txt', mimeType: 'text/plain', buffer: Buffer.from('Reference item') });
  assert.equal(await page.locator('.attachment').count(), 1);
  await page.getByRole('button', { name: '移除 reference.txt' }).click();
  assert.equal(await page.locator('.attachment').count(), 0);
  await page.locator('#more-toggle').click();
  await clickAction('rename');
  await page.locator('#name-input').fill('我的闪电剑');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  assert.equal(await page.locator('#project-title').innerText(), '我的闪电剑');
  await page.locator('#more-toggle').click();
  await clickAction('settings');
  await page.locator('#theme-select').selectOption('dark');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await screenshot('desktop-dark');
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  assert.equal(await page.locator('.result').count(), 2);
  await page.locator('#more-toggle').click();
  await clickAction('settings');
  await page.locator('#theme-select').selectOption('light');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await screenshot('mobile-conversation');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('#home').click();
  await screenshot('mobile-empty');
  await page.getByRole('checkbox', { name: '专业模式' }).check();
  await screenshot('mobile-expert');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('checkbox', { name: '专业模式' }).uncheck();
  await page.setViewportSize({ width: 320, height: 740 });
  await page.getByLabel('模型', { exact: true }).selectOption('gpt-5.6-terra');
  await page.getByLabel('思考强度', { exact: true }).selectOption('extreme');
  await screenshot('mobile-narrow');
  assert.equal(await page.evaluate(() => {
    const controls = ['attach', 'model-select', 'reasoning-select', 'send'].map(id => document.getElementById(id).getBoundingClientRect());
    return controls.every((rect, i) => rect.left >= 0 && rect.right <= innerWidth && (i === 0 || controls[i - 1].right <= rect.left));
  }), true, 'Composer controls must not overlap at 320px');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#projects-toggle').click();
  await page.locator('[data-project]:visible').click();
  assert.equal(await page.locator('#project-title').innerText(), '我的闪电剑');
  await page.locator('#more-toggle').click();
  await clickAction('account');
  assert.match(await page.locator('#dialog').innerText(), /不会消耗额度/);
  await page.keyboard.press('Escape');
  await page.locator('[data-action="test-game"]').last().click();
  assert.match(await page.locator('#dialog').innerText(), /尚未构建/);
  await page.keyboard.press('Escape');
  await page.locator('#projects-toggle').click();
  await page.locator('[data-delete]').click();
  await page.locator('#confirm-delete').click();
  assert.equal(await page.locator('#welcome').isVisible(), true);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'passed', canvasOpaquePixels: nonblank, screenshots: 10, checks: ['empty state', 'one logo and 29px greeting', 'hot mode switch preserves draft and running task', 'model and reasoning persistence', 'lock settings during generation', 'version choice', 'stop and resume', 'results', 'preview recolor', 'PNG download', 'JSON export with generation settings', 'attachments', 'rename', 'theme', 'persistence', 'mobile overflow', '320px control overlap', 'history', 'account and game boundaries', 'deletion'], errors }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
