import { createServer } from 'vite'
import react from '@vitejs/plugin-react'
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import path from 'node:path'

const server = await createServer({ configFile: false, root: process.cwd(), plugins: [react()], optimizeDeps: { entries: ['test-results/beginner-minimal/react.html'] }, server: { host: '127.0.0.1', port: 5198, strictPort: false } })
await server.listen()
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${server.resolvedUrls.local[0]}test-results/beginner-minimal/react.html`)
  await page.locator('.agent-minimal').waitFor()
  assert.equal(await page.locator('.chat-welcome-recommendations').isVisible(), true)
  const composer = await page.locator('.agent-composer').boundingBox()
  const recommendations = await page.locator('.chat-welcome-recommendations').boundingBox()
  assert.ok(recommendations.y >= composer.y + composer.height)
  const greeting = await page.locator('.chat-welcome h2').textContent()
  await page.getByRole('button', { name: '换一组推荐' }).click()
  assert.equal(await page.locator('.chat-welcome h2').textContent(), greeting)
  await page.locator('.chat-welcome-options button').first().click()
  assert.ok((await page.locator('textarea').inputValue()).length > 0)
  assert.equal(await page.evaluate(() => window.calls.start), 0)
  assert.equal(await page.locator('.chat-welcome h2').evaluate(el => getComputedStyle(el).fontSize), '29px')
  await page.screenshot({ path: path.resolve('test-results/beginner-minimal/react-empty.png') })
  await page.locator('textarea').fill('制作闪电剑')
  await page.getByLabel('专业模式', { exact: true }).check()
  assert.equal(await page.locator('textarea').inputValue(), '制作闪电剑')
  assert.equal(await page.locator('.chat-welcome-recommendations').isVisible(), true)
  await page.getByLabel('专业模式', { exact: true }).uncheck()
  await page.getByLabel('模型', { exact: true }).selectOption('account-custom-model')
  assert.equal(await page.getByRole('button', { name: '发送', exact: true }).isDisabled(), true)
  await page.locator('textarea').press('Enter')
  assert.equal(await page.evaluate(() => window.calls.start), 0)
  await page.waitForFunction(() => !document.querySelector('.minimal-quota-preferences select').disabled)
  assert.equal(await page.getByLabel('模型', { exact: true }).inputValue(), 'account-custom-model')
  await page.getByLabel('思考强度', { exact: true }).selectOption('extreme')
  await page.waitForFunction(() => !document.querySelector('.minimal-quota-preferences select').disabled)
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await page.getByLabel('专业模式', { exact: true }).check()
  assert.equal(await page.evaluate(() => window.calls.start), 1)
  assert.equal(await page.evaluate(() => window.calls.cancel), 0)
  await page.getByLabel('专业模式', { exact: true }).uncheck()
  assert.equal(await page.getByLabel('模型', { exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: '停止任务', exact: true }).click()
  assert.equal(await page.evaluate(() => window.calls.cancel), 1)
  assert.equal(await page.evaluate(() => window.calls.start), 1)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: path.resolve('test-results/beginner-minimal/react-mobile.png') })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.setViewportSize({ width: 320, height: 740 })
  await page.screenshot({ path: path.resolve('test-results/beginner-minimal/react-narrow.png') })
  const noOverlap = await page.evaluate(() => {
    const model = document.querySelector('.minimal-quota-preferences').getBoundingClientRect()
    const send = document.querySelector('.agent-send-button').getBoundingClientRect()
    return model.right <= send.left && send.right <= innerWidth
  })
  assert.equal(noOverlap, true, 'Preference controls must not overlap send on narrow screens')
  assert.deepEqual(errors, [])
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto(`${server.resolvedUrls.local[0]}test-results/beginner-minimal/react.html?choices`)
  await page.locator('.discussion-choice-cards').waitFor()
  assert.equal(await page.locator('.discussion-choice-cards button').count(), 3)
  assert.equal(await page.locator('.minimal-engineering-handoff').count(), 0)
  assert.equal(await page.getByRole('button', { name: '开始制作', exact: true }).count(), 0)
  assert.ok(!(await page.locator('.agent-markdown').innerText()).includes('modmind-choices'))
  await page.screenshot({ path: path.resolve('test-results/beginner-minimal/discussion-cards.png') })
  await page.getByRole('button', { name: '先聊合成配方', exact: true }).click()
  assert.equal(await page.evaluate(() => window.calls.choices[0].action), 'discussion')
  assert.equal(await page.locator('.discussion-choice-cards button:disabled').count(), 3)
  await page.reload()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.discussion-choice-cards').waitFor()
  await page.screenshot({ path: path.resolve('test-results/beginner-minimal/discussion-cards-mobile.png') })
  await page.getByRole('button', { name: '按这个方案制作', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => window.calls.choices[0]), { label: '按这个方案制作', prompt: '确认制作蓝色闪电剑', action: 'engineering' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.deepEqual(errors, [])
  console.log('React workbench integration passed: shared callbacks, hot UI switch, draft retention, account model list, preference save barrier, mobile layout.')
} finally { await browser.close(); await server.close() }
