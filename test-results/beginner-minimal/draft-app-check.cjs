const { _electron: electron } = require('playwright');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'modmind-auto-draft-'));
  const documents = path.join(profile, 'Documents');
  await fs.mkdir(documents);
  const env = { ...process.env, ELECTRON_RENDERER_URL: 'http://localhost:5173' };
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ args: ['.', `--user-data-dir=${profile}`], env });
  try {
    const page = await app.firstWindow();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await app.evaluate(({ app, ipcMain }, documents) => {
      app.setPath('documents', documents);
      globalThis.draftCalls = [];
      const replace = (name, handler) => { ipcMain.removeHandler(name); ipcMain.handle(name, handler); };
      replace('device:getState', () => ({ status: 'connected', configured: true, keyStatus: 'ACTIVE', balanceCents: 1000 }));
      replace('device:getAiPreferences', () => ({ model: 'gpt-5.6-sol', reasoningLevel: 'medium', fastMode: false }));
      replace('device:listModels', () => [{ id: 'gpt-5.6-sol' }]);
      replace('beginner-codex:prepare', () => ({ status: 'ready' }));
      replace('ai:createCode', async (event, prompt, sessionId, backend, profile, options) => {
        globalThis.draftCalls.push({ prompt, sessionId, backend, profile, options });
        const answer = options.workbenchPhase === 'discussion' ? '我们先做一个基础版本，你准备使用哪个游戏平台？\n<modmind-choices>[{"label":"先聊玩法","prompt":"先聊玩法","action":"discussion"},{"label":"讨论配方","prompt":"先讨论配方","action":"discussion"},{"label":"按这个方案制作","prompt":"确认按当前方案制作","action":"engineering"}]</modmind-choices>' : '工程任务已接收。';
        await new Promise(resolve => setTimeout(resolve, 250));
        event.sender.send('ai:output', { kind: 'answer', content: answer, time: new Date().toISOString(), sessionId, projectPath: options.projectPath, conversationId: options.conversationId, generation: options.generation, turnId: options.turnId, backend });
        return { summary: answer, finalResponse: answer, tasks: [], files: [], changedFiles: [], tests: [], warnings: [], intent: options.workbenchPhase === 'discussion' ? 'informational' : 'engineering' };
      });
    }, documents);
    await page.evaluate(() => localStorage.setItem('modmind-ui-mode', 'beginner'));
    await page.reload();
    await page.locator('.minimal-project-start').waitFor();
    await page.screenshot({ path: 'test-results/beginner-minimal/centered-start.png' });
    const composer = await page.locator('.agent-composer').boundingBox();
    const viewportHeight = await page.evaluate(() => innerHeight);
    assert.ok(Math.abs(composer.y + composer.height / 2 - viewportHeight / 2) < 60);
    await page.getByLabel('创作需求', { exact: true }).fill('我想做一把闪电剑');
    await page.getByRole('button', { name: '发送', exact: true }).click();
    await page.getByRole('button', { name: '按这个方案制作', exact: true }).waitFor();
    assert.equal(await page.getByRole('dialog').count(), 0);
    const first = await app.evaluate(() => globalThis.draftCalls);
    assert.equal(first.length, 1);
    const root = first[0].options.projectPath;
    assert.equal(path.dirname(root), path.join(documents, 'modmindproject'));
    assert.equal((await fs.readdir(path.dirname(root))).filter(name => name.startsWith('project-')).length, 1);
    let manifest = JSON.parse(await fs.readFile(path.join(root, 'modmind.project.json'), 'utf8'));
    assert.deepEqual(manifest.draft.target, {});
    assert.match(first[0].prompt, /空壳项目/);
    assert.equal(await fs.stat(path.join(root, 'build.gradle')).then(() => true, () => false), false);
    await page.getByRole('button', { name: '按这个方案制作', exact: true }).click();
    await page.getByRole('button', { name: '停止任务', exact: true }).waitFor();
    await page.getByRole('button', { name: '按这个方案制作', exact: true }).waitFor();
    assert.equal((await app.evaluate(() => globalThis.draftCalls))[1].options.workbenchPhase, 'discussion');
    await page.locator('.agent-composer textarea').fill('做一个 Bedrock 1.21.100 模组');
    await page.getByRole('button', { name: '发送', exact: true }).click();
    await page.getByRole('button', { name: '按这个方案制作', exact: true }).waitFor();
    manifest = JSON.parse(await fs.readFile(path.join(root, 'modmind.project.json'), 'utf8'));
    assert.deepEqual(manifest.draft.target, { minecraftVersion: '1.21.100', loader: 'bedrock', kind: 'mod' });
    await page.getByRole('button', { name: '按这个方案制作', exact: true }).click();
    await page.getByText('工程任务已接收。', { exact: true }).waitFor({ timeout: 60000 });
    manifest = JSON.parse(await fs.readFile(path.join(root, 'modmind.project.json'), 'utf8'));
    assert.equal(manifest.draft, undefined);
    assert.equal(manifest.loader, 'bedrock');
    assert.equal(manifest.path, root);
    const calls = await app.evaluate(() => globalThis.draftCalls);
    assert.equal(calls.length, 4);
    assert.equal(calls[3].options.workbenchPhase, undefined);
    assert.equal(new Set(calls.map(call => call.options.conversationId)).size, 1);
    await page.reload();
    await page.getByText('工程任务已接收。', { exact: true }).waitFor();
    await page.screenshot({ path: 'test-results/beginner-minimal/draft-upgraded.png' });
    assert.deepEqual(errors, []);
    console.log('PASS: automatic Documents project, first message sent once, no dialog, missing-details discussion, real in-place template generation, shared conversation and reload, centered composer. AI mocked.');
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
