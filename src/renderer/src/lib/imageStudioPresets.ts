export const imageStudioPresetGroups = [...new Set(imageStudioPresets.map(preset => preset.group))]
export function findImageStudioPreset(id?: string): ImageStudioPreset | undefined {
  return imageStudioPresets.find(preset => preset.id === id)
}

/** The template belongs to its generator, so shared prompt nodes are never overwritten. */
export function imageWorkflowPrompt(data: { presetId?: string; presetPrompt?: string }, prompt = ''): string {
  const preset = findImageStudioPreset(data.presetId)
  if (!preset) return prompt.trim()
  const template = (data.presetPrompt ?? preset.prompt).trim()
  if (!template) return ''
  return `按以下预设生成图片。【】内为可替换的默认内容，不要把括号或说明文字绘制到图片中。\n\n${template}${prompt.trim() ? `\n\n补充要求（如与预设中的主体、材质或配色示例冲突，以此处为准）：\n${prompt.trim()}` : ''}`
}
