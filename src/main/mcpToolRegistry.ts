export function unavailableMcpTools(handlers: ExternalAgentBridgeHandlers, hasPluginTarget = false): string[] {
  return [
    ...Object.entries(MCP_TOOL_HANDLERS).filter(([, key]) => typeof handlers[key] !== 'function').map(([name]) => name),
    ...(!hasPluginTarget ? Object.entries(MCP_TOOL_ROUTES).filter(([, action]) => action.startsWith('plugin_')).map(([name]) => name) : [])
  ]
}
