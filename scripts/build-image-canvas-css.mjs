import fs from 'node:fs/promises'
import path from 'node:path'
import postcss from 'postcss'
import tailwind from '@tailwindcss/postcss'

const root = path.resolve(import.meta.dirname, '..')
const vendor = path.join(root, 'feature-plugins/image-studio/vendor/open-canvas')
const source = `@import "tailwindcss/theme.css";\n@import "tailwindcss/utilities.css" source(none);\n@source "${path.join(vendor,'components').replaceAll('\\','/')}";\n@theme inline {
  --color-background: var(--theme-canvas); --color-foreground: var(--theme-text);
  --color-border: var(--theme-line); --color-primary: var(--theme-action);
  --color-primary-foreground: var(--theme-on-action); --color-secondary: var(--theme-panel);
  --color-secondary-foreground: var(--theme-text); --color-muted: var(--theme-panel);
  --color-muted-foreground: var(--theme-muted); --color-accent: var(--theme-selected);
  --color-accent-foreground: var(--theme-text); --color-destructive: var(--theme-danger);
  --color-input: var(--theme-line); --color-ring: var(--theme-focus);
  --color-popover: var(--theme-raised); --color-popover-foreground: var(--theme-text);
  --radius-sm: 4px; --radius-md: 6px; --radius-lg: 8px; --radius-xl: 10px;
}`
const result = await postcss([tailwind({base:root,optimize:true})]).process(source,{from:path.join(root,'image-canvas-tailwind.css')})
const css = postcss.parse(result.css)
css.walkRules(rule => {
  let parent = rule.parent
  while(parent && parent.type !== 'root') { if(parent.type === 'rule' || /keyframes$/.test(parent.name ?? '')) return; parent=parent.parent }
  rule.selectors = rule.selectors.map(selector => {
    if(selector === ':root' || selector === ':host') return '.image-canvas-scope'
    const tag = selector.match(/^[a-z][\w-]*/i)?.[0] ?? ''
    return `${tag}:where(.image-canvas-scope, .image-canvas-scope *)${tag ? selector.slice(tag.length) : selector.startsWith('*') ? selector.slice(1) : selector}`
  })
})
css.walkDecls(decl => {
  if(decl.prop === '--color-white') decl.value='var(--theme-text)'
  if(decl.prop === '--color-black') decl.value='var(--theme-shadow)'
  if(/^--color-(?:zinc|neutral|gray|slate)-/.test(decl.prop)) decl.value=Number(decl.prop.match(/\d+$/)?.[0]) >= 700 ? 'var(--theme-panel)' : 'var(--theme-muted)'
  if(/^(?:lab|lch|oklab|oklch|rgb|rgba|hsl|hsla)\(/.test(decl.value)) {
    decl.value = /background|--color-background/.test(decl.prop) ? 'var(--theme-surface)' : /border|outline|ring/.test(decl.prop) ? 'var(--theme-line)' : /shadow/.test(decl.prop) ? 'var(--theme-shadow)' : 'var(--theme-text)'
  }
  if(/#[\da-f]{3,8}\b/i.test(decl.value)) {
    const token=/^(?:background|--tw-gradient)/.test(decl.prop)?'--theme-surface':/border|outline|ring/.test(decl.prop)?'--theme-line':/shadow/.test(decl.prop)?'--theme-shadow':'--theme-text'
    decl.value=decl.value.replace(/#[\da-f]{3,8}\b/gi,`var(${token})`)
  }
})
const output='/* Generated by scripts/build-image-canvas-css.mjs. Scoped utilities; no global reset. */\n'+css.toString()+'\n'
const destination=path.join(vendor,'canvas-utilities.css')
if(await fs.readFile(destination,'utf8').catch(()=>null)!==output) await fs.writeFile(destination,output)
console.log('Built scoped image canvas utilities.')
