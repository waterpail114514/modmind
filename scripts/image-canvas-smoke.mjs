import {chromium} from 'playwright'
import fs from 'node:fs/promises'
import path from 'node:path'
import {checkCanvasInteractions} from './fixtures/image-canvas-interaction-checks.mjs'
const output=path.resolve('test-results/image-canvas')
await fs.mkdir(output,{recursive:true})
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:900}})
const errors=[],requests=[]
page.on('pageerror',error=>errors.push(error.message))
page.on('console',message=>{if(message.type()==='error'&&!message.text().includes('kaspersky-labs.com'))errors.push(message.text())})
page.on('request',request=>{if(!request.url().includes('kaspersky-labs.com')&&!request.url().startsWith('http://127.0.0.1:4328')&&!request.url().startsWith('data:')&&!request.url().startsWith('blob:'))requests.push(request.url())})
const check=(condition,message)=>{if(!condition)throw new Error(message)}
try{
 await page.goto('http://127.0.0.1:4328',{waitUntil:'commit'})
 await page.getByTestId('open-canvas-workspace').waitFor()
 await checkCanvasInteractions(page,output,'desktop-1440')
 await page.setViewportSize({width:1080,height:680})
 await checkCanvasInteractions(page,output,'desktop-1080')
 await page.setViewportSize({width:1440,height:900})
 await page.screenshot({path:path.join(output,'initial.png')})
 const graph={format:'open-canvas-document-v1',title:'图像画布验收',graph:{version:1,viewport:{x:100,y:80,zoom:1},nodes:[{id:'image-test',type:'image',position:{x:120,y:60},width:400,data:{title:'测试图片',prompt:'蓝色水晶',model:'image-fixture',inputMode:'generate',aspectRatio:'1:1',resolution:'1K',count:1}}],edges:[]}}
 await page.getByTestId('open-canvas-import').setInputFiles({name:'canvas.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(graph))})
 await page.locator('.react-flow__node').first().waitFor()
 await page.locator('.react-flow__node').first().click()
 await page.getByLabel('图片提示词',{exact:true}).waitFor()
 await page.getByLabel('批量生成数量',{exact:true}).selectOption('3')
 await page.screenshot({path:path.join(output,'selected-light-1440.png')})
 await page.getByRole('button',{name:'生成',exact:true}).click()
 await page.getByRole('button',{name:'送去处理',exact:true}).first().waitFor({timeout:20000})
 check(await page.evaluate(()=>window.canvasQa.requests[0]?.count===3),'batch count did not reach the existing image service')
 check(await page.locator('.react-flow__node select option').count()===3,'not all three generated images reached the node history')
 await page.locator('.react-flow__node select').selectOption('2')
 await page.screenshot({path:path.join(output,'batch-light-1440.png')})
 await page.getByRole('button',{name:'送去处理',exact:true}).first().click()
 await page.getByRole('button',{name:'PerfectPixel',exact:true}).click()
 await page.getByRole('button',{name:'撤销上一步',exact:true}).click()
 await page.getByRole('button',{name:'另存为',exact:true}).click()
 check(await page.evaluate(()=>window.canvasQa.saved.length===1&&window.canvasQa.processed[0]==='perfect-pixel'),'process or save handoff failed')
 await page.getByRole('tab',{name:'生成',exact:true}).click()
 await page.locator('.react-flow__node').first().click()
 check(await page.getByLabel('批量生成数量',{exact:true}).inputValue()==='3','batch setting lost when switching panels')
 await page.getByLabel('图片提示词',{exact:true}).fill('失败后保留结果')
 await page.getByRole('button',{name:'生成',exact:true}).click()
 await page.getByText('第 2 张生成失败，已保留第 1 张',{exact:false}).first().waitFor({timeout:20000})
 await page.screenshot({path:path.join(output,'partial-failure.png')})
 await page.getByLabel('图片提示词',{exact:true}).fill('恢复后重试')
 await page.getByRole('button',{name:'生成',exact:true}).click()
 await page.waitForFunction(()=>window.canvasQa.requests.length===3)
 await page.getByRole('button',{name:'正在生成',exact:true}).waitFor({state:'hidden'})
 await page.getByRole('button',{name:'切换主题',exact:true}).click()
 await page.screenshot({path:path.join(output,'batch-dark-1440.png')})
 await page.setViewportSize({width:1080,height:680})
 await page.screenshot({path:path.join(output,'batch-dark-1080.png')})
 const bounds=await page.getByLabel('图片提示词',{exact:true}).boundingBox()
 check(bounds&&bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=1080&&bounds.y+bounds.height<=680,'prompt outside minimum desktop window')
 await page.getByRole('button',{name:'切换主题',exact:true}).click()
 await page.screenshot({path:path.join(output,'batch-light-1080.png')})
 await page.getByRole('button',{name:'切换页面',exact:true}).click()
 await page.keyboard.press('Delete')
 await page.getByRole('button',{name:'切换页面',exact:true}).click()
 check(await page.locator('.react-flow__node').count()===1,'hidden canvas intercepted Delete')
 await page.reload()
 await page.locator('.react-flow__node').first().waitFor()
 await page.locator('.react-flow__node').first().click()
 check(await page.getByLabel('批量生成数量',{exact:true}).inputValue()==='3','batch count not persisted after reload')
 check(await page.getByLabel('图片提示词',{exact:true}).inputValue()==='恢复后重试','prompt not persisted after reload')
 // The Electron renderer is bundled locally; disconnect only online services in this HTTP fixture.
 await page.goto('http://127.0.0.1:4328/?offline=1',{waitUntil:'commit'})
 await page.locator('.react-flow__node').first().waitFor()
 await page.locator('.react-flow__node').first().click()
 await page.screenshot({path:path.join(output,'offline-restored.png')})
 check(errors.length===0,'browser errors: '+errors.join('\n'))
 check(requests.length===0,'unexpected external network requests: '+requests.join('\n'))
 await fs.writeFile(path.join(output,'verification.json'),JSON.stringify({success:true,errors,externalRequests:requests,checks:['left-button-pan','right-button-box-selection','right-click-menu','left-button-node-drag','selection-blur-recovery','double-click-node-menu','create-image-node','wheel-zoom-in-out','pointer-centered-zoom','prompt-double-click','prompt-wheel-scroll','packaged-renderer','batch-generation','process-handoff','undo-processing','save','partial-failure','retry','light-dark','1080x680','hidden-shortcuts','reload','offline'],fixtureOnly:true},null,2))
 console.log('PASS image canvas UI smoke; screenshots: '+output)
}catch(error){await page.screenshot({path:path.join(output,'failure.png')});await fs.writeFile(path.join(output,'failure.json'),JSON.stringify({error:String(error),errors,externalRequests:requests,body:await page.locator('body').innerText()},null,2));throw error}
finally{await browser.close()}
