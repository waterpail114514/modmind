import { _electron as electron } from 'playwright'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const root = path.resolve(import.meta.dirname, '..')
const output = path.join(root, 'test-results', 'unified-upgrade-live')
await mkdir(output, { recursive: true })
const userData = path.join(output, 'user-data')
const projectParent = path.join(output, 'projects')
await mkdir(projectParent, { recursive: true })
const errors = []
const app = await electron.launch({ args: [root, `--user-data-dir=${userData}`], cwd: root, timeout: 45000 })
try {
  console.log('APP', await app.evaluate(({ app }) => app.getPath('userData')))
  const page = await app.firstWindow()
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(30000)
  await page.waitForFunction(() => Boolean(window.modmind?.resourcePacks))
  await app.evaluate(({ dialog }, parent) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [parent] }) }, projectParent)
  const project = await page.evaluate(async () => window.modmind.project.create({ name: `Plugin Live ${Date.now()}`, kind: 'server-plugin', loader: 'paper', minecraftVersion: '1.21.1' }))
  if (!project) throw new Error('create cancelled')
  console.log('PROJECT', project.path)
  await writeFile(path.join(output, 'project.json'), JSON.stringify(project, null, 2))
  await page.reload()
  await page.waitForFunction(() => Boolean(window.modmind))
  if (!await page.getByRole('checkbox', { name: '专业模式' }).isChecked()) await page.locator('.expert-mode-toggle').click()
  await page.waitForFunction(() => document.querySelector('.app-shell')?.classList.contains('mode-advanced'))
  await page.getByText(project.name, { exact: true }).first().click()
  await page.waitForTimeout(500)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('app:openView', 'modpack-resourcepacks'))
  await page.getByRole('heading', { name: '资源包', exact: true }).waitFor()
  await page.getByRole('button', { name: '新建', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建资源包' })
  await dialog.getByLabel('名称', { exact: true }).fill('live-pack')
  await dialog.getByLabel('描述', { exact: true }).fill('Live resource pack')
  await dialog.getByRole('button', { name: '创建', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  const texture = await sharp({ create: { width: 16, height: 16, channels: 4, background: '#42b983' } }).png().toBuffer()
  await page.evaluate(async ({ project, image }) => {
    await window.modmind.resourcePacks.write(project.path, 'live-pack', 'assets/live/textures/item/example.png', image, null)
    await window.modmind.resourcePacks.write(project.path, 'live-pack', 'assets/live/models/item/example.json', JSON.stringify({ parent: 'minecraft:item/generated', textures: { layer0: 'live:item/example' } }), null)
  }, { project, image: `data:image/png;base64,${texture.toString('base64')}` })
  await page.getByTitle('刷新资源包', { exact: true }).click()
  await page.getByTitle('assets/live/textures/item/example.png', { exact: true }).click()
  await page.locator('.resource-pack-image img').waitFor()
  await page.screenshot({ path: path.join(output, 'resource-pack-desktop.png') })
  await page.getByRole('button', { name: '校验', exact: true }).click()
  await page.getByText('结构校验通过', { exact: false }).waitFor()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(680, 860))
  await page.waitForTimeout(300)
  await page.screenshot({ path: path.join(output, 'resource-pack-narrow.png') })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1280, 900))
  const zip = path.join(output, 'live-pack.zip')
  await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, zip)
  await page.getByRole('button', { name: '导出 ZIP', exact: true }).click()
  await page.getByText(`已导出：${zip}`, { exact: true }).waitFor()
  console.log('EXPORT', (await readFile(zip)).length)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('app:openView', 'modpack-server'))
  await page.getByRole('heading', { name: '服务端核心与运行配置' }).waitFor()
  await page.screenshot({ path: path.join(output, 'plugin-server.png') })
  await writeFile(path.join(output, 'ui-report.json'), JSON.stringify({ project, errors, zip }, null, 2))
  if (errors.length) throw new Error(errors.join('\n'))
  if (process.argv.includes('--build')) {
    console.log('BUILD START')
    const artifact = await page.evaluate(project => window.modmind.minecraft.buildProject(project.path), project)
    console.log('BUILD', artifact)
    await writeFile(path.join(output, 'artifact.json'), JSON.stringify(artifact, null, 2))
  }
} finally { await app.close() }
