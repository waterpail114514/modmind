import { chromium } from 'playwright'
import { createServer } from 'vite'
import react from '@vitejs/plugin-react'
import { promises as fs } from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'

const directory = path.resolve('test-results/game-control-ui'); await fs.mkdir(directory, { recursive: true })
const server = await createServer({ configFile: false, root: process.cwd(), plugins: [react()], logLevel: 'error', optimizeDeps: { noDiscovery: true, include: ['react', 'react-dom/client', 'lucide-react'], entries: ['docs/game-control-compatibility/ui.html'] }, server: { host: '127.0.0.1', port: 0, watch: null } })
await server.listen()
const browser = await chromium.launch({ headless: true, executablePath: process.env.MODMIND_UI_BROWSER })
const errors = [], assertions = []
try {
  const page = await browser.newPage({ viewport: { width: 1080, height: 680 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(server.resolvedUrls.local[0] + 'docs/game-control-compatibility/ui.html')
  await page.getByRole('button', { name: '启动后台测试' }).waitFor()
  await page.screenshot({ path: path.join(directory, 'idle-dark-1080.png') })
  await page.getByRole('checkbox', { name: '不加载项目 Mod' }).check()
  await page.getByRole('button', { name: '启动后台测试' }).click()
  await page.getByRole('status').filter({ hasText: '正在准备游戏' }).waitFor()
  await page.screenshot({ path: path.join(directory, 'preparing-dark-1080.png') })
  await page.getByRole('img', { name: /Minecraft 游戏画面/ }).waitFor()
  await page.getByRole('button', { name: 'W', exact: true }).click()
  await page.getByRole('textbox', { name: '输入文字' }).fill('中文测试')
  await page.getByRole('button', { name: '输入到游戏' }).click()
  const image = page.getByRole('img', { name: /Minecraft 游戏画面/ }), box = await image.boundingBox()
  await image.click({ position: { x: box.width * 0.4, y: box.height * 0.5 } })
  await page.getByRole('button', { name: 'W', exact: true }).waitFor({ state: 'visible' })
  await page.waitForFunction(() => !document.querySelector('button[disabled]')?.textContent?.includes('W'))
  await page.mouse.move(box.x + box.width * 0.3, box.y + box.height * 0.4); await page.mouse.down(); await page.mouse.move(box.x + box.width * 0.6, box.y + box.height * 0.5, { steps: 5 }); await page.mouse.up()
  await page.getByRole('button', { name: '暂停 AI', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'AI 已暂停' }).waitFor()
  assert(await page.getByRole('button', { name: 'W', exact: true }).isDisabled())
  await page.getByRole('button', { name: '手动接管', exact: true }).click()
  await page.getByRole('status').filter({ hasText: '由你控制' }).waitFor()
  await page.screenshot({ path: path.join(directory, 'human-dark-1080.png') })
  await page.getByRole('button', { name: '恢复 AI', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'AI 后台控制中' }).waitFor()
  await page.evaluate(() => { window.failNext = true })
  await page.getByRole('button', { name: 'W', exact: true }).click()
  await page.getByRole('alert').waitFor()
  await page.screenshot({ path: path.join(directory, 'failure-dark-1080.png') })
  await page.getByRole('button', { name: 'W', exact: true }).click()
  await page.getByRole('alert').waitFor({ state: 'hidden' })
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(button => button.textContent === 'W')?.disabled)
  await page.screenshot({ path: path.join(directory, 'ready-dark-1080.png') })
  await page.evaluate(() => window.setDark(false)); await page.screenshot({ path: path.join(directory, 'ready-light-1080.png') })
  const layout = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, buttons: [...document.querySelectorAll('.background-game-toolbar button')].map(button => { const r = button.getBoundingClientRect(); return { text: button.textContent, x: r.x, right: r.right, bottom: r.bottom } }) }))
  assert(layout.scrollWidth <= layout.width); assert(layout.buttons.every(button => button.x >= 0 && button.right <= layout.width))
  await page.setViewportSize({ width: 1440, height: 900 }); await page.screenshot({ path: path.join(directory, 'ready-light-1440.png') })
  await page.getByRole('button', { name: '松开全部按键' }).click(); await page.getByRole('button', { name: '停止测试' }).click()
  await page.getByRole('button', { name: '启动后台测试' }).waitFor()
  const calls = await page.evaluate(() => window.calls)
  assert(calls.some(call => call.input.operation === 'drag')); assert(calls.some(call => call.input.operation === 'click')); assert(calls.some(call => call.input.text === '中文测试'))
  assert.equal(errors.length, 0); assertions.push('start/preparing/ready', 'key/text/click/drag', 'pause/takeover/resume', 'failure/retry', 'release/stop', '1080x680 dark/light', '1440x900', 'no horizontal overflow')
  await fs.writeFile(path.join(directory, 'verification.json'), JSON.stringify({ fixture: 'real production component, simulated transport with historical game image', assertions, layout, calls, errors }, null, 2))
  console.log(JSON.stringify({ directory, assertions }))
} finally { await browser.close(); await server.close() }
